import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Generates schemas/generated.ts from the committed JSON Schemas. json-schema-to-ts
 * needs the schemas as `as const` TS literals — resolveJsonModule widens JSON
 * strings to `string`, which breaks FromSchema — so the schemas are emitted as
 * readonly literals here. tests/schemas-sync.test.ts regenerates this file and
 * fails if it drifts, keeping the types pinned to the schemas.
 */
const root = new URL("../", import.meta.url).pathname;
const schemas = [
  { name: "caseSchema", file: "schemas/case.schema.json" },
  { name: "stateSchema", file: "schemas/state.schema.json" },
];

let out = `// GENERATED by scripts/gen-types.ts from the JSON Schemas — do not edit.
// Run \`bun run gen:types\` to regenerate; tests/schemas-sync.test.ts enforces sync.
import type { FromSchema } from "json-schema-to-ts";

`;
for (const schema of schemas) {
  const json = JSON.parse(readFileSync(join(root, schema.file), "utf8"));
  out += `export const ${schema.name} = ${JSON.stringify(json, null, 2)} as const;\n\n`;
}
out += `export type EvalCase = FromSchema<typeof caseSchema>;\nexport type SystemState = FromSchema<typeof stateSchema>;\n`;

const outFlag = process.argv.indexOf("--out");
const outPath =
  outFlag !== -1 ? process.argv[outFlag + 1]! : join(root, "schemas/generated.ts");
writeFileSync(outPath, out);
console.log(`Regenerated ${outPath}`);